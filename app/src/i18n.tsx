const DICT: Record<Lang, Dict> = { pt: PT, en: EN, es: ES, fr: FR, de: DE };

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  nf: (n: number) => string;
  needsChoice: boolean;
};
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => storedLang() ?? detect());
  const [needsChoice, setNeedsChoice] = useState<boolean>(() => storedLang() === null);

  const value = useMemo<Ctx>(() => {
    const fmt = new Intl.NumberFormat(LOCALE[lang]);
    const t = (key: string, vars?: Record<string, string | number>) => {
      let s = DICT[lang][key] ?? DICT.pt[key] ?? key;
      if (vars) for (const k in vars) s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      return s;
    };
    return {
      lang,
      needsChoice,
      t,
      nf: (n: number) => fmt.format(n),
      setLang: (l: Lang) => {
        localStorage.setItem(LS, l);
        setLangState(l);
        setNeedsChoice(false);
      },
    };
  }, [lang, needsChoice]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n fora do I18nProvider");
  return c;
}
