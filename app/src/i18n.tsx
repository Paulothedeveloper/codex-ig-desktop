export type Lang = "pt" | "en" | "es" | "fr" | "de";
export const LANGS: { code: Lang; native: string; locale: string }[] = [
  { code: "pt", native: "Português", locale: "pt-BR" },
  { code: "en", native: "English", locale: "en-US" },
  { code: "es", native: "Español", locale: "es-ES" },
  { code: "fr", native: "Français", locale: "fr-FR" },
  { code: "de", native: "Deutsch", locale: "de-DE" },
];
const LOCALE: Record<Lang, string> = { pt: "pt-BR", en: "en-US", es: "es-ES", fr: "fr-FR", de: "de-DE" };
const LS = "codexig_lang";

export function storedLang(): Lang | null {
  const v = localStorage.getItem(LS);
  return v && LANGS.some((l) => l.code === v) ? (v as Lang) : null;
}
function detect(): Lang {
  const p = (navigator.language || "pt").slice(0, 2).toLowerCase();
  return (LANGS.find((l) => l.code === p)?.code as Lang) || "pt";
}

